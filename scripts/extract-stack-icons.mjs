// Extracts the 17 needed tech icons from node_modules/tech-stack-icons
// and generates src/data/stackIcons.ts (light + dark SVGs).
// Re-run after `npm i tech-stack-icons` to add/change icons.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const WANT = [
  'react',
  'nextjs',
  'html5',
  'js',
  'bootstrap5',
  'tailwindcss',
  'nodejs2',
  'npm',
  'mongodb',
  'supabase',
  'sqlite',
  'vercel',
  'github',
  'n8n',
  'vscode',
  'opencode',
  'pwa',
]

const pkgPath = join(ROOT, 'node_modules', 'tech-stack-icons', 'dist', 'index.js')
const src = readFileSync(pkgPath, 'utf8')

const start = src.indexOf('var f=') + 'var f='.length
let depth = 0
let end = start
for (; end < src.length; end++) {
  if (src[end] === '{') depth++
  else if (src[end] === '}') {
    depth--
    if (depth === 0) break
  }
}
if (depth !== 0) throw new Error('Failed to brace-match the icon map')

const icons = Function(`return (${src.slice(start, end + 1)})`)()

const lines = [
  '// Generated by scripts/extract-stack-icons.mjs — do not edit manually.',
  '// Run `npm i tech-stack-icons && node scripts/extract-stack-icons.mjs` to regenerate.',
  '',
  'export type StackIconName =',
  ...WANT.map((n, i) => `  | '${n}'${i === WANT.length - 1 ? '' : ''}`),
  '',
  'export const STACK_ICONS: Record<StackIconName, { light: string; dark: string }> = {',
  ...WANT.map((n) => {
    const def = icons[n]
    if (!def) throw new Error(`Icon not found in package: ${n}`)
    return `  ${n}: { light: ${JSON.stringify(def.svg.light)}, dark: ${JSON.stringify(def.svg.dark)} },`
  }),
  '}',
  '',
]

const out = join(ROOT, 'src', 'data', 'stackIcons.ts')
writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${out} (${WANT.length} icons)`)